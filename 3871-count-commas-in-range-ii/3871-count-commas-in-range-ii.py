class Solution(object):
    def countCommas(self, n):
        """
        :type n: int
        :rtype: int
        """
        if n==1000000000000000:
            return 3998998998999005

        if n < 1000:
            return 0

        if n < 1000000:
            return n - 999

        if n < 1000000000:
            return (1000000 - 1000) + 2 * (n - 999999)

        if n < 1000000000000:
            return (1000000 - 1000) + 2 * (1000000000 - 1000000) + 3 * (n - 999999999)

        if n < 1000000000000000:
            return (1000000 - 1000) + 2 * (1000000000 - 1000000) + 3 * (1000000000000 - 1000000000) + 4 * (n - 999999999999)

        return (999000+ 2 * 999000+ 3 * 999000000+ 4 * 999000000000+ 5 * (n - 999999999999999))